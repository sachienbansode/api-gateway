SELECT 'application' AS object, count(*) FROM applications WHERE code = 'cmots'
UNION ALL SELECT 'categories',  count(*) FROM api_categories WHERE application = 'cmots'
UNION ALL SELECT 'upstream',    count(*) FROM upstreams      WHERE name = 'cmots'
UNION ALL SELECT 'endpoints',   count(*) FROM endpoints      WHERE application = 'cmots'
UNION ALL SELECT 'parameters',  count(*) FROM endpoint_params p
     JOIN endpoints e ON e.name = p.endpoint WHERE e.application = 'cmots'
UNION ALL SELECT 'fields',      count(*) FROM endpoint_fields f
     JOIN endpoints e ON e.name = f.endpoint WHERE e.application = 'cmots';

-- Per category, with the field count — the quick sanity read.
SELECT c.label AS category, count(*) AS endpoints,
       sum((SELECT count(*) FROM endpoint_fields f WHERE f.endpoint = e.name)) AS fields
  FROM endpoints e JOIN api_categories c
    ON c.application = e.application AND c.code = e.category
 WHERE e.application = 'cmots'
 GROUP BY c.label, c.sort_order ORDER BY c.sort_order;
